"""Premium ("AAA") tier on top of data/hq_filter.py: keep(text, kind, path) -> (ok, reason).

Corpus v4's rules see only content. Package documents also carry their file path, which lets this
tier drop whole classes of low-value files, and it tightens the content rules:

code
  * no vendored, built, bundled, generated, fixture, locale or snapshot paths; no .min/.bundle,
    .d.ts, protobuf stubs, setup.py; .cjs/.mjs only under src/ or lib/ (elsewhere they are build output)
  * Python must parse (ast.parse): syntax-valid, no Python 2 leftovers
  * 300-60,000 characters, mean line length <= 80, no line over 250
  * real program structure (a function, class, impl, module ... keyword); >= 600 characters
  * no generated SDKs: known generated families (amazonka, aws-sdk, azure-mgmt, google-cloud,
    mypy-boto3, *-stubs) and every package in which >= 20 % of the code files carry a generator
    marker (package_flags) are dropped whole, code and docs
  * files with >= 40 non-blank lines carry comments or docstrings on >= 2 % of them
  * no transpiler or bundler output: no run of >= 4 blank lines, no import of a numbered chunk module
    (`from "../1827.js"`)
prose
  * allow-list: READMEs and files under docs/guide/tutorial/manual/wiki paths, or named like
    DESIGN, ARCHITECTURE, API, USAGE, FAQ, OVERVIEW, QUICKSTART, TUTORIAL, GUIDE, INDEX
  * never: changelogs, licences, notices, author lists, codes of conduct, security policies,
    templates, egg-info lists, and instruction files written for AI coding assistants
    (AGENTS, SKILL, CLAUDE, GEMINI, copilot/cursor rules): they are often model-written,
    and corpus policy excludes outputs of closed models
  * >= 500 characters, >= 8 % English stopwords, URLs <= 15 % of the characters, table rows
    <= 40 % of the lines (generated model/property pages are mostly tables), Sphinx directive
    lines <= 30 % (autodoc stubs carry no prose)
text (keep_text, corpus v6: books, papers, encyclopedias, educational pages without a package path)
  * the prose content rules above without the path rules; documents up to 3 M characters stay whole
"""
from __future__ import annotations

import ast
import re

import hq_filter

DROP_DIR = re.compile(r"(^|/)(vendor|vendored|third[_-]?party|node_modules|dist|build|_build|target|site-packages|"
                      r"migrations|fixtures?|testdata|test_data|__snapshots__|snapshots|locales?|i18n|generated|"
                      r"gen|bundles?|min|out|coverage|\.git|\.github)(/|$)", re.I)
DROP_FILE = re.compile(r"(\.min\.|\.bundle\.|\.d\.ts$|_pb2(_grpc)?\.py$|\.pb\.go$|(^|/)setup\.py$)", re.I)
MODULE_JS = re.compile(r"\.(cjs|mjs)$", re.I)
SRC_DIR = re.compile(r"(^|/)(src|lib)/", re.I)
STRUCTURE = re.compile(r"\b(def|class|fn|func|function|impl|struct|trait|module|interface|enum|data|instance|"
                       r"newtype|object|lambda|let|const|export)\b|=>")
DOC_LINE = re.compile(r"^\s*(#|//|/\*|\*|--|\{-|\"\"\"|''')")
URL = re.compile(r"https?://\S+")
DIRECTIVE = re.compile(r"^\s*(\.\. [\w:-]+::|:[\w-]+:)")
TABLE_ROW = re.compile(r"^\s*\|.*\|\s*$")
GENERATED_MORE = re.compile(r"(?i)(derived from aws service descriptions|openapi-generator\.tech|generated by: http|"
                            r"do not modify|this file is generated|autogenerated by|generated with|swagger codegen)")
BLANK_RUN = re.compile(r"\n[ \t]*\n[ \t]*\n[ \t]*\n[ \t]*\n")
CHUNK_IMPORT = re.compile(r"""(?:\bfrom\s+|\brequire\(\s*|\bimport\(\s*)['"](?:\.{1,2}/)+\d+(?:\.[cm]?js)?['"]""")
SDK_PACKAGE = re.compile(r"^[a-z]+:(amazonka|aws-sdk|azure-mgmt|google-cloud-|googleapis|mypy-boto3|botocore-stubs|"
                         r"types-aiobotocore|[\w.-]+-stubs$)", re.I)

PROSE_ALLOW_DIR = re.compile(r"(^|/)(docs?|documentation|guides?|tutorials?|manual|handbook|wiki|book)(/|$)", re.I)
PROSE_ALLOW_NAME = re.compile(r"^(readme|design|architecture|api|usage|getting[-_ ]?started|faq|overview|introduction|intro|"
                              r"quickstart|tutorial|guide|index|concepts|cookbook|examples?)\b", re.I)
PROSE_DENY_NAME = re.compile(r"^(changelog|changes|history|news|release|releases|release[-_ ]?notes|license|licence|copying|"
                             r"notice|authors|contributors|code[-_ ]of[-_ ]conduct|security|maintainers|funding|sources|"
                             r"requires|dependency_links|top_level|pkg-info|agents|skill|claude|gemini|copilot|cursor|"
                             r"\.cursorrules|pull_request_template|issue_template|cmakelists|makefile|todo)\b", re.I)


def _base(path: str) -> str:
    return path.rsplit("/", 1)[-1]


def generated(text: str) -> bool:
    return bool(hq_filter.GENERATED.search(text[:4000]) or GENERATED_MORE.search(text[:4000]))


def package_flags(docs) -> set:
    """Sources (registry:name) to drop whole: generated-SDK families, and packages whose code files carry
    a generator marker in >= 20 % of cases. docs: iterable of (source, kind, text)."""
    total, gen, bad = {}, {}, set()
    for source, kind, text in docs:
        if SDK_PACKAGE.match(source):
            bad.add(source)
        if kind == "code":
            total[source] = total.get(source, 0) + 1
            gen[source] = gen.get(source, 0) + generated(text)
    return bad | {s for s, n in total.items() if gen.get(s, 0) >= 0.2 * n}


def keep_code(text: str, path: str) -> tuple[bool, str]:
    if generated(text):
        return False, "generated"
    ok, why = hq_filter.keep_code(text)
    if not ok:
        return False, f"v4-{why}"
    if DROP_DIR.search(path.rsplit("/", 1)[0] if "/" in path else ""):
        return False, "path"
    if DROP_FILE.search(path) or (MODULE_JS.search(path) and not SRC_DIR.search(path)):
        return False, "file-type"
    if not 600 <= len(text) <= 60_000:
        return False, "size"
    lines = text.split("\n")
    lens = [len(ln) for ln in lines]
    if sum(lens) / len(lines) > 80 or max(lens) > 250:
        return False, "line-length"
    if path.endswith(".py"):
        try:
            ast.parse(text)
        except (SyntaxError, ValueError, RecursionError, MemoryError):
            return False, "python-syntax"
    if not STRUCTURE.search(text):
        return False, "no-structure"
    if BLANK_RUN.search(text):
        return False, "blank-runs"
    if CHUNK_IMPORT.search(text):
        return False, "bundled"
    nonblank = [ln for ln in lines if ln.strip()]
    if len(nonblank) >= 40 and sum(1 for ln in nonblank if DOC_LINE.match(ln)) < 0.02 * len(nonblank):
        return False, "undocumented"
    return True, "ok"


def keep_prose(text: str, path: str) -> tuple[bool, str]:
    name = _base(path)
    if PROSE_DENY_NAME.match(name):
        return False, "denied-file"
    if not (PROSE_ALLOW_NAME.match(name) or PROSE_ALLOW_DIR.search(path)):
        return False, "not-documentation"
    return _prose_content(text)


TEXT_MAX = 3_000_000


def keep_text(text: str) -> tuple[bool, str]:
    """Prose without a package path (books, papers, encyclopedias, educational web pages): the content rules of
    keep_prose. Long documents are kept whole up to TEXT_MAX characters (long-context training); the v4 rules,
    which cap at 100k characters, judge the first 100k."""
    if len(text) > TEXT_MAX:
        return False, "too-long"
    return _prose_content(text[:100_000])


def _prose_content(text: str) -> tuple[bool, str]:
    ok, why = hq_filter.keep_prose(text)
    if not ok:
        return False, f"v4-{why}"
    if len(text) < 500:
        return False, "short"
    words = [w.lower() for w in hq_filter.WORD.findall(text)]
    if sum(w in hq_filter.STOPWORDS for w in words) < 0.08 * len(words):
        return False, "not-english"
    if sum(len(u) for u in URL.findall(text)) > 0.15 * len(text):
        return False, "links"
    lines = [ln for ln in text.split("\n") if ln.strip()]
    if sum(1 for ln in lines if TABLE_ROW.match(ln)) > 0.4 * len(lines):
        return False, "tables"
    if sum(1 for ln in lines if DIRECTIVE.match(ln)) > 0.3 * len(lines):
        return False, "autodoc"
    if generated(text):
        return False, "generated"
    return True, "ok"


def keep(text: str, kind: str, path: str) -> tuple[bool, str]:
    return keep_code(text, path) if kind == "code" else keep_prose(text, path)
