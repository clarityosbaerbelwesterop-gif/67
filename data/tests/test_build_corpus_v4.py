"""Corpus v4: the high-quality filter and near-duplicate removal."""
import sys
from collections import Counter
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import build_corpus_v4 as B  # noqa: E402
import hq_filter as H  # noqa: E402

CODE = "\n".join(f"def f{i}(x, y):\n    total = x + y * {i}\n    return total if total > 0 else -total\n" for i in range(12))
PROSE = ("The parser reads the configuration file and returns a dictionary with all of the options. If a value is "
         "missing, it falls back to the default that the user set in the environment. ") * 4


def test_keep_rules():
    assert H.keep(CODE, "code") == (True, "ok")
    assert H.keep("x = 1\n", "code") == (False, "short")
    assert H.keep("# Code generated by protoc-gen-go. DO NOT EDIT.\n" + CODE, "code")[1] == "generated"
    assert H.keep("# a comment line of some length\n" * 20, "code")[1] in ("comments", "repetition")
    assert H.keep("data = '" + "QUJD" * 37 + "'\n" + CODE, "code")[1] == "blob"
    assert H.keep(PROSE, "general") == (True, "ok") or H.keep(PROSE, "general")[1].startswith("top-")
    assert H.keep("Un prompt es una plantilla de mensajes que elige el usuario para el modelo. " * 5, "general")[1] == "not-english"
    assert H.keep("x" * 150, "general")[1] == "length"


def test_near_duplicates_are_caught_and_distinct_texts_kept():
    nd = B.NearDup()
    a = B.sketch(PROSE + " first variant of the closing sentence here")
    b = B.sketch(PROSE + " second variant of the closing sentence here")
    c = B.sketch(CODE)
    assert not nd.seen(a) and nd.seen(b), "a near duplicate"
    assert not nd.seen(c), "different text"
    assert np.array_equal(B.sketch(CODE), c), "deterministic"


def test_filter_store_copies_token_spans_of_kept_documents(tmp_path, monkeypatch):
    vocab = [bytes([i]) for i in range(256)]
    docs = [CODE, CODE, "x = 1\n"]  # the second is an exact duplicate, the third too short
    toks = np.concatenate([np.frombuffer(d.encode(), np.uint8).astype(np.uint16).tolist() + [B.EOS] for d in docs]).astype(np.uint16)
    src = tmp_path / "src"
    src.mkdir()
    toks.tofile(src / "train.bin")
    dst = tmp_path / "dst"
    dst.mkdir()
    stats = Counter()
    res = B.filter_store("code", src, vocab + [b""] * (B.EOS + 1 - 256), stats, B.NearDup(), set(), dst=dst)
    out = np.fromfile(dst / "train.bin", np.uint16)
    assert res["docs"] == 1 and out.tolist() == toks[: len(CODE) + 1].tolist()
    assert stats["code:drop:duplicate"] == 1 and stats["code:drop:short"] == 1
