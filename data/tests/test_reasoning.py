"""Reasoning store (data/build_reasoning.py): every family yields verified, well-formed documents, program traces
match a real run, and the human-written sources are filtered as documented."""
import importlib.util
import random
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
_spec = importlib.util.spec_from_file_location("build_reasoning", ROOT / "data" / "build_reasoning.py")
br = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(br)

FORMAT = re.compile(r"^Problem: .+\n\nThinking:\n.+\n\nAnswer:[ \n].+\n$", re.S)


def _draw(fn, r, sc):
    for _ in range(20):
        try:
            return fn(r, sc)
        except br.Reject:
            continue
    raise AssertionError(f"{fn.__name__}: no instance")


def test_every_family_is_verified_and_well_formed():
    for name, (fn, _) in br.FAMILIES.items():
        r = random.Random(11)
        for sc in (0.05, 0.4, 0.9):
            for _ in range(4 if name == "program" else 8):
                text = _draw(fn, r, sc)  # each generator asserts its answer against an independent check
                assert FORMAT.match(text), (name, text[:200])


def test_program_answer_is_the_real_output():
    r = random.Random(3)
    for _ in range(15):
        text = _draw(br.g_program, r, 0.5)
        src = text.split("```python\n", 1)[1].split("```", 1)[0]
        out = []
        env = {"__builtins__": dict(br.SAFE, print=lambda *a: out.append(" ".join(map(str, a))))}
        exec(compile(src, "<t>", "exec"), env)  # noqa: S102 - generated by the closed grammar under test
        assert text.rsplit("Answer:", 1)[1].strip() == "\n".join(out).strip()


def test_long_processes_are_long():
    r = random.Random(5)
    lens = [len(_draw(br.g_hanoi, r, 0.99)), len(_draw(br.g_ledger, r, 0.99)), len(_draw(br.g_program, r, 0.99))]
    assert min(lens) > 3000, lens


def test_synth_is_deterministic():
    assert br.synth(123, 5) == br.synth(123, 5)
    assert br.synth(123, 5) != br.synth(124, 5)


def test_gsm8k_annotations_are_checked_and_removed():
    good = {"question": "Tom has 3 bags of 4 apples. How many apples?",
            "answer": "He has 3*4=<<3*4=12>>12 apples.\n#### 12"}
    text, why = br.gsm8k_doc(good)
    assert why == "ok" and "<<" not in text and text.endswith("Answer: 12\n")
    bad = {"question": good["question"], "answer": "He has 3*4=<<3*4=13>>13 apples.\n#### 13"}
    assert br.gsm8k_doc(bad) == (None, "wrong-annotation")


def test_aqua_rationale_must_reach_the_correct_option():
    row = {"question": "A train covers 120 km in 2 hours. What is its speed in km/h?",
           "options": ["A)40", "B)50", "C)60", "D)70", "E)80"],
           "rationale": "Speed is distance divided by time.\n120 / 2 = 60 km/h.\nCheck: 60 * 2 = 120 km.\nAnswer: C", "correct": "C"}
    text, why = br.aqua_doc(row)
    assert why == "ok" and text.endswith("Answer: C) 60\n") and "Answer: C\n" not in text.split("Answer:")[0]
    assert br.aqua_doc(dict(row, correct="B")) == (None, "wrong-letter")


def test_aqua_rejects_unverified_or_inconsistent_rationales():
    row = {"question": "A train covers 120 km in 2 hours. What is its speed in km/h?",
           "options": ["A)40", "B)50", "C)60", "D)70", "E)80"], "correct": "C",
           "rationale": "Speed is distance divided by time.\n120 / 2 = 60 km/h.\nCheck: 60 * 2 = 120 km.\nAnswer: C"}
    assert br.aqua_doc(dict(row, rationale=row["rationale"].replace("60 * 2 = 120", "60 * 2 = 130")))[1] == \
        "wrong-equation"
    assert br.aqua_doc(dict(row, rationale="Speed is distance over time, so it is sixty.\nAnswer: C"))[1] in \
        ("unverified", "length")
    assert br.aqua_doc(dict(row, question=row["question"].replace("120 km", "150 km")))[1] == "numbers-differ"
