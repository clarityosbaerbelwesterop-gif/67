def test_good_code_and_docs_are_kept():
    assert premium.keep(GOOD_PY, "code", "pkg-1.0/pkg/stats.py") == (True, "ok")
    assert premium.keep(GOOD_README, "general", "pkg-1.0/README.md") == (True, "ok")
    assert premium.keep(GOOD_README, "general", "pkg-1.0/docs/usage.md") == (True, "ok")


def test_paths_and_file_types():
    assert premium.keep(GOOD_PY, "code", "pkg-1.0/vendor/pkg/stats.py")[1] == "path"
    assert premium.keep(GOOD_PY, "code", "pkg-1.0/dist/stats.py")[1] == "path"
    assert premium.keep(GOOD_PY, "code", "pkg-1.0/setup.py")[1] == "file-type"
    assert premium.keep(GOOD_PY.replace('"""', "#"), "code", "pkg/index.cjs")[1] == "file-type"


def test_python_must_parse_and_generated_code_is_dropped():
    assert premium.keep(GOOD_PY.replace("def stdev(", "def stdev(("), "code", "p/s.py")[1] == "python-syntax"
    assert premium.keep("# Code generated by protoc. DO NOT EDIT.\n" + GOOD_PY, "code", "p/s.py")[1] == "generated"


def test_prose_allow_and_deny_lists():
    assert premium.keep(GOOD_README, "general", "pkg/AGENTS.md")[1] == "denied-file"
    assert premium.keep(GOOD_README, "general", "pkg/CHANGELOG.md")[1] == "denied-file"
    assert premium.keep(GOOD_README, "general", "pkg/notes.txt")[1] == "not-documentation"
    table = "# Model\n\n## Properties\n\n" + "\n".join(f"| **f{i}** | **String** | field {i} | [optional] |" for i in range(30))
    assert premium.keep(GOOD_README + "\n" + table, "general", "pkg/docs/Model.md")[1] in ("tables", "v4-top-2gram",
                                                                                         "v4-top-3gram", "v4-top-4gram")


def test_generated_packages_are_dropped_whole():
    gen = "# This file is generated. Do not modify.\n" + GOOD_PY
    docs = [("pypi:sdkgen", "code", gen)] * 3 + [("pypi:sdkgen", "code", GOOD_PY)] * 7 + \
           [("pypi:clean", "code", gen)] + [("pypi:clean", "code", GOOD_PY)] * 9 + \
           [("hackage:amazonka-s3", "code", GOOD_PY)]
    assert premium.package_flags(docs) == {"pypi:sdkgen", "hackage:amazonka-s3"}


def test_transpiler_and_bundler_output_is_dropped():
    spaced = GOOD_PY.replace("import math\n", "import math\n\n\n\n\n")
    assert premium.keep(spaced, "code", "p/s.py")[1] == "blank-runs"
    js = "// helpers for the CLI runner\n" + GOOD_PY.replace('"""', "//").replace(
        "import math", 'import x from "../1827.js";')
    assert premium.keep(js, "code", "pkg/src/run.js")[1] == "bundled"
