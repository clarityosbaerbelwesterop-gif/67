def v2_fixture(root: Path) -> dict:
    """Tiny v2 stores, a v2 docs cache containing RUBY_DUPLICATE and a v2 done list containing rubygems:oldgem."""
    meta = {}
    for kind, n in (("code", 300), ("general", 120)):
        d = root / "out" / f"{kind}-v2"
        d.mkdir(parents=True)
        array("H", [i % 8000 for i in range(n - 1)] + [v2.EOS]).tofile((d / "train.bin").open("wb"))
        array("H", [7, 8, v2.EOS]).tofile((d / "train.val.bin").open("wb"))
        shutil.copy(v2.TOKENIZER, d / "tokenizer.json")
        meta[kind] = {"tokens": n, "val_tokens": 3, "dtype": "uint16", "vocab_size": 8192, "bin": "train.bin", "val_bin": "train.val.bin",
                      "mix": {kind: 2}, "mix_fractions": {kind: 1.0}}
        (d / "train.meta.json").write_text(json.dumps(meta[kind]))
    docs = root / "cache" / "v2" / "docs"
    docs.mkdir(parents=True)
    h = hashlib.sha1(v2.NORM.sub(" ", RUBY_DUPLICATE.strip()).encode()).hexdigest()
    (docs / "code-train.jsonl").write_text(json.dumps({"h": h, "k": "code", "s": "rubygems:old", "p": "x.rb", "t": RUBY_DUPLICATE.strip()}) + "\n")
    (root / "cache" / "v2" / "done.jsonl").write_text(json.dumps({"task": "rubygems:oldgem", "status": "ok"}) + "\n")
    ev = root / "evals"
    ev.mkdir()
    (ev / "mbpp.jsonl").write_text(json.dumps({"text": "Write a function.", "test_list": [CONTAMINATED]}) + "\n")
    (ev / "humaneval.jsonl").write_text(json.dumps({"prompt": "def f():", "canonical_solution": "return 1"}) + "\n")
    (ev / "gsm8k.jsonl").write_text(json.dumps({"question": "1+1?", "answer": "2"}) + "\n")
    return meta | {"v2_hash": h}


def parquet_fixture(path: Path) -> Path | None:
    try:
        import pyarrow as pa
        import pyarrow.parquet as pq
    except ImportError:
        return None
    rows = [("Educational text number %d. " % i) * 40 for i in range(3)] + ["too short"]
    pq.write_table(pa.table({"text": rows}), path)
    return path


def u16(p: Path) -> array:
    a = array("H")
    a.frombytes(p.read_bytes())
    return a


@pytest.mark.skipif(not HAVE_FORGE, reason="needs target/release/forge and data/stores/base/tokenizer.json")
def test_end_to_end_build_with_root(tmp_path, monkeypatch):
    fx = v2_fixture(tmp_path)
    net = FakeNet(routes())
    monkeypatch.setattr(reg, "fetch", net)
    monkeypatch.setattr(reg, "reachable", lambda *a, **k: False)
    pk = tmp_path / "packages.txt"
    pk.write_text("maven:org.example:lib\nmaven:org.example:gpl-lib\nrubygems:fixgem\nrubygems:oldgem\nhackage:fixpkg\n")
    args = ["--root", str(tmp_path), "--packages", str(pk), "--evals", str(tmp_path / "evals"), "--max-disk-gb", "1"]
    pq = parquet_fixture(tmp_path / "fw.parquet")
    if pq:
        args += ["--parquet", str(pq)]
    assert v3.main(args) == 0

    out = tmp_path / "out"
    tok = v2.TOKENIZER.read_bytes()
    for name in v3.STORES:
        d = out / name
        assert {p.name for p in d.iterdir()} >= {"train.bin", "train.val.bin", "tokenizer.json", "train.meta.json", "manifest.json"}
        meta = json.loads((d / "train.meta.json").read_text())
        assert meta["dtype"] == "uint16" and meta["vocab_size"] == 8192 and (d / "tokenizer.json").read_bytes() == tok
        assert meta["tokens"] * 2 == (d / "train.bin").stat().st_size and meta["val_tokens"] * 2 == (d / "train.val.bin").stat().st_size
        man = json.loads((d / "manifest.json").read_text())
        assert man["sha256"]["train.bin"] == hashlib.sha256((d / "train.bin").read_bytes()).hexdigest()
        assert man["pipeline"].startswith("data/build_corpus_v3.py")
        assert max(u16(d / "train.bin")) < 8192
    code, gen, base = (json.loads((out / n / "manifest.json").read_text()) for n in v3.STORES)
    assert code["tokens"] == fx["code"]["tokens"] + code["new"]["tokens"] and code["new"]["tokens"] > 0
    assert gen["tokens"] == fx["general"]["tokens"] + gen["new"]["tokens"] and gen["new"]["tokens"] > 0
    assert (out / "code-v3" / "train.bin").read_bytes().startswith((out / "code-v2" / "train.bin").read_bytes())
    for f in ("train.bin", "train.val.bin"):
        assert (out / "base-v3" / f).read_bytes() == (out / "code-v3" / f).read_bytes() + (out / "general-v3" / f).read_bytes()
    assert u16(out / "code-v3" / "train.bin")[-1] == v2.EOS
    assert set(code["mix"]) == {"code-v2", "maven", "rubygems", "hackage"}
    assert {"general-v2", "maven", "rubygems", "hackage"} <= set(gen["mix"]) and (pq is None or "fineweb-edu" in gen["mix"])
    assert base["mix"] == {"code": sum(code["mix"].values()), "general": sum(gen["mix"].values())}

    man = tmp_path / "manifests"
    sources = {s["task"]: s for s in json.loads((man / "sources.json").read_text())}
    assert "rubygems:oldgem" not in sources and not any("oldgem" in u for u in net.calls)
    assert sources["maven:org.example:gpl-lib"]["status"] == "rejected-licence"
    for t in ("maven:org.example:lib", "rubygems:fixgem", "hackage:fixpkg"):
        s = sources[t]
        assert s["status"] == "ok" and reg.licence_ok(s["license"]) and s["attribution"] and len(s["sha256"]) == 64 and s["url"]
    assert sources["rubygems:fixgem"]["kept"] == 2 and sources["rubygems:fixgem"]["files"] == 3  # dup of v2 dropped
    assert sources["maven:org.example:lib"]["kept"] == 2 and sources["maven:org.example:lib"]["files"] == 4  # contaminated + generated dropped
    filters = json.loads((man / "filters.json").read_text())["filters"]
    assert filters["duplicate_v2"] == 1 and filters["contaminated"] == 1 and filters["generated"] == 1
    stores = json.loads((man / "stores.json").read_text())
    assert stores["evals_decontaminated_against"] == ["gsm8k", "humaneval", "mbpp"]
    assert stores["fineweb_edu"]["status"] == ("ok" if pq else "skipped: huggingface.co unreachable")
    assert stores["packages"]["maven"] == {"ok": 1, "rejected-licence": 1}

    index = (out / "base-v3" / "docs.sha1").read_bytes()
    digests = {index[i:i + 20].hex() for i in range(0, len(index), 20)}
