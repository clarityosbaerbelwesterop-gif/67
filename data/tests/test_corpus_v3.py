def tgz(files: dict[str, str | bytes]) -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tf:
        for name, data in files.items():
            raw = data.encode() if isinstance(data, str) else data
            info = tarfile.TarInfo(name)
            info.size = len(raw)
            tf.addfile(info, io.BytesIO(raw))
    return buf.getvalue()


def zipb(files: dict[str, str]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        for name, data in files.items():
            zf.writestr(name, data)
    return buf.getvalue()


def gem(files: dict[str, str]) -> bytes:
    buf = io.BytesIO()
    parts = {"metadata.gz": gzip.compress(b"--- !ruby/object:Gem::Specification\n"), "data.tar.gz": tgz(files)}
    with tarfile.open(fileobj=buf, mode="w") as tf:
        for name, raw in parts.items():
            info = tarfile.TarInfo(name)
            info.size = len(raw)
            tf.addfile(info, io.BytesIO(raw))
    return buf.getvalue()


def pom(lics: list[str], parent: tuple | None = None, doctype: bool = False) -> bytes:
    lic = "".join(f"<license><name>{x}</name></license>" for x in lics)
    par = f"<parent><groupId>{parent[0]}</groupId><artifactId>{parent[1]}</artifactId><version>{parent[2]}</version></parent>" if parent else ""
    head = '<!DOCTYPE x [<!ENTITY a "aaaa">]>' if doctype else ""
    return (f'<?xml version="1.0"?>{head}<project xmlns="http://maven.apache.org/POM/4.0.0">{par}<name>Fixture</name>'
            f"<url>https://example.org/lib</url><licenses>{lic}</licenses><developers><developer><name>Ada</name></developer>"
            "</developers></project>").encode()


def metadata(release: str, versions: list[str]) -> bytes:
    vs = "".join(f"<version>{v}</version>" for v in versions)
    return f"<metadata><versioning><release>{release}</release><versions>{vs}</versions></versioning></metadata>".encode()


class FakeNet:
    """URL -> bytes; records every request."""

    def __init__(self, routes: dict[str, bytes]):
        self.routes, self.calls = routes, []

    def __call__(self, url, timeout=90, accept=None, max_bytes=reg.MAX_DOWNLOAD):  # noqa: ANN001
        self.calls.append(url)
        return self.routes.get(url)


