def test_plan_interleaves_registries_and_skips_v2(monkeypatch):
    seen = {}

    def lister(r):
        def f(n, skip):
            seen[r] = skip
            return [x for x in [f"{r}1", f"{r}2", f"{r}3"] if x not in skip][:n]
        return f

    monkeypatch.setattr(reg, "LISTS", {r: lister(r) for r in v3.REGISTRIES})
    a = v3.argparse.Namespace(packages=None, registries=["maven", "pypi"], limit=2)
    tasks = v3.plan(a, {"pypi:pypi1", "npm:x"})
    assert tasks == [("maven", "maven1"), ("pypi", "pypi2"), ("maven", "maven2"), ("pypi", "pypi3")]
    assert seen == {"maven": set(), "pypi": {"pypi1"}}


