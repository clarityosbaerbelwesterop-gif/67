"""High-quality filter for corpus v4: keep(text, kind) -> (ok, reason).

Content rules only (the v3 token stores carry no file paths). A document is
dropped when any rule fires. Thresholds follow the Gopher / RefinedWeb heuristics
for prose and the read-only audit of 1,000 v2 documents (2026-10-12) for code,
where these rules flagged 14.9 % of the documents and 21.5 % of the characters:
generated code without a marker, repeated-line blobs, data tables, base64/hex
dumps, comment-only files, non-English prose and near-empty files.
"""
from __future__ import annotations

import re
from collections import Counter

GENERATED = re.compile(
    r"(?i)(do not edit|auto-?generated|automatically generated|generated by (protoc|the protocol buffer|swagger|openapi"
    r"|thrift|grpc|stainless|fern|autorest|apiextractor)|openapi-generator|this code was generated by|this file was generated"
    r"|file generated from our openapi|code generated by microsoft|generated from a template|@generated\b)")
BASE64_RUN = re.compile(r"[A-Za-z0-9+/=]{120,}")
HEX_RUN = re.compile(r"(?:0x[0-9a-fA-F]{1,8}\s*,\s*){32,}")
COMMENT = re.compile(r"^\s*(#|//|/\*|\*|--|;|%|\{-|\")")
BULLET = re.compile(r"^\s*([-*•]|\d+[.)])\s")
WORD = re.compile(r"[A-Za-z]+")
STOPWORDS = frozenset("the be to of and a in that have i it for not on with he as you do at this but his by from they we say her "
                      "she or an will my one all would there their what so up out if about who get which go me when make can "
                      "like time no just him know take people into year your good some could them see other than then now "
                      "look only come its over think also back after use two how our work first well way even new want "
                      "because any these give day most us is are was were been has had does did should may must".split())


def _ratio(n: int, d: int) -> float:
    return n / d if d else 0.0


def repeated_line_share(lines: list, min_len: int = 20) -> float:
    """Share of characters in lines of >= min_len characters that occur more than once."""
    long_lines = [ln.strip() for ln in lines if len(ln.strip()) >= min_len]
    counts = Counter(long_lines)
    total = sum(len(ln) for ln in lines) or 1
    return sum(len(ln) * c for ln, c in counts.items() if c > 1) / total


def top_ngram_share(words: list, n: int) -> float:
    """Gopher: share of the characters of all words covered by the most frequent n-gram."""
    if len(words) < n + 1:
        return 0.0
    grams = Counter(tuple(words[i:i + n]) for i in range(len(words) - n + 1))
    gram, count = grams.most_common(1)[0]
    return _ratio(sum(len(w) for w in gram) * count, sum(len(w) for w in words))


def keep_code(text: str) -> tuple[bool, str]:
    if len(text) < 200:
        return False, "short"
    if GENERATED.search(text[:4000]):
        return False, "generated"
    lines = text.split("\n")
    lens = [len(ln) for ln in lines]
    if sum(lens) / len(lines) > 100 or _ratio(sum(1 for n in lens if n > 200), len(lines)) > 0.01:
        return False, "long-lines"
    chars = [c for c in text if not c.isspace()]
    if _ratio(sum(c.isalnum() for c in chars), len(chars)) < 0.45:
        return False, "symbols"
    if _ratio(sum(c.isdigit() for c in chars), len(chars)) > 0.25:
        return False, "digits"
    nonblank = [ln for ln in lines if ln.strip()]
    if _ratio(sum(1 for ln in nonblank if COMMENT.match(ln)), len(nonblank)) > 0.8:
        return False, "comments"
    if repeated_line_share(lines) > 0.5:
        return False, "repetition"
    if BASE64_RUN.search(text) or HEX_RUN.search(text):
        return False, "blob"
    return True, "ok"


def keep_prose(text: str) -> tuple[bool, str]:
    if not 200 <= len(text) <= 100_000:
        return False, "length"
    if GENERATED.search(text[:4000]):
        return False, "generated"
    chars = [c for c in text if not c.isspace()]
    if _ratio(sum(c.isalnum() for c in chars), len(chars)) < 0.6:
        return False, "symbols"
    if _ratio(sum(ord(c) > 127 for c in chars), len(chars)) > 0.2:
        return False, "non-ascii"
    words = [w.lower() for w in WORD.findall(text)]
    if not words or _ratio(sum(w in STOPWORDS for w in words), len(words)) < 0.06:
        return False, "not-english"
    mean = sum(map(len, words)) / len(words)
    if not 3 <= mean <= 10:
        return False, "word-length"
    lines = text.split("\n")
    if repeated_line_share(lines) > 0.3:
        return False, "repetition"
    for n, cap in ((2, 0.20), (3, 0.18), (4, 0.16)):
        if top_ngram_share(words, n) > cap:
            return False, f"top-{n}gram"
    nonblank = [ln for ln in lines if ln.strip()]
    if _ratio(sum(1 for ln in nonblank if BULLET.match(ln)), len(nonblank)) > 0.9:
        return False, "bullets"
    return True, "ok"


def keep(text: str, kind: str) -> tuple[bool, str]:
    """kind: "code" (the code store) or "general" (prose)."""
    return keep_code(text) if kind == "code" else keep_prose(text)
