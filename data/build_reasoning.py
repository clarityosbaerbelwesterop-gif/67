def g_hanoi(r: random.Random, sc: float) -> str:
    n = 2 + int(sc * 7)
    pegs = {"A": list(range(n, 0, -1)), "B": [], "C": []}
    moves = []

    def solve(k: int, a: str, c: str, b: str) -> None:
        if k:
            solve(k - 1, a, b, c)
            moves.append((k, a, c))
            solve(k - 1, b, c, a)

    solve(n, "A", "C", "B")
    steps = []
    for i, (k, a, c) in enumerate(moves, 1):
        assert pegs[a] and pegs[a][-1] == k and (not pegs[c] or pegs[c][-1] > k)
        pegs[c].append(pegs[a].pop())
        steps.append(f"{i}. Disk {k} from {a} to {c}. A={pegs['A']} B={pegs['B']} C={pegs['C']}")
    assert pegs["C"] == list(range(n, 0, -1)) and len(moves) == 2 ** n - 1
    return doc(f"Tower of Hanoi with {n} disks on peg A (disk 1 is the smallest). Move them all to peg C, one disk at "
               "a time, never a larger disk on a smaller one. List every move and the pegs after it (bottom first).",
               steps, f"{len(moves)} moves; all disks are on C")


GOODS = {"apples": "apple", "pears": "pear", "bolts": "bolt", "nuts": "nut", "cables": "cable", "lamps": "lamp",
         "boxes": "box", "valves": "valve"}


def _n(q: int, g: str) -> str:
    return f"{q} {GOODS[g] if q == 1 else g}"


def g_ledger(r: random.Random, sc: float) -> str:
    goods = r.sample(sorted(GOODS), 3 + int(sc * 3 * r.random()))
    stock = {g: r.randint(0, 40) for g in goods}
    start = dict(stock)
    events, steps = [], []
    for i in range(6 + int(sc * 120)):
        g, q = r.choice(goods), r.randint(1, 25)
        kind = r.choice(["receive", "ship", "ship", "return"])
        events.append((kind, q, g))
    for i, (kind, q, g) in enumerate(events, 1):
        if kind == "ship" and stock[g] < q:
            steps.append(f"{i}. Ship {_n(q, g)}: only {stock[g]} in stock, order skipped. {g} = {stock[g]}.")
            continue
        old = stock[g]
        stock[g] += -q if kind == "ship" else q
        sign = "-" if kind == "ship" else "+"
        steps.append(f"{i}. {kind.capitalize()} {_n(q, g)}: {old} {sign} {q} = {stock[g]}.")
    # independent recomputation
    chk = dict(start)
    for kind, q, g in events:
        if kind == "ship":
            if chk[g] >= q:
                chk[g] -= q
        else:
            chk[g] += q
    assert chk == stock
    ev = "; ".join(f"{i}. {kind} {_n(q, g)}" for i, (kind, q, g) in enumerate(events, 1))
    st = ", ".join(_n(v, g) for g, v in start.items())
    return doc(f"A warehouse starts with {st}. Events in order: {ev}. A shipment larger than the stock is skipped. "
               "What is the final stock?", steps, ", ".join(_n(stock[g], g) for g in goods))


def g_calendar(r: random.Random, sc: float) -> str:
    d0 = datetime.date(r.randint(1990, 2040), r.randint(1, 12), r.randint(1, 28))
    n = r.randint(5, 40 + int(sc * 2500))
    d, left, steps = d0, n, []
    while left:
        last = calendar.monthrange(d.year, d.month)[1]
        to_end = last - d.day
        if left <= to_end:
            d = d.replace(day=d.day + left)
            steps.append(f"{left} days remain and fit in {calendar.month_name[d.month]} {d.year}: day {d.day}.")
            left = 0
        else:
            left -= to_end + 1
            leap = " (leap year)" if d.month == 2 and last == 29 else ""
            d = (d.replace(day=1) + datetime.timedelta(days=32)).replace(day=1)
            steps.append(f"{to_end + 1} days to reach {d.isoformat()} ({calendar.month_name[(d.month - 2) % 12 + 1]} "
                         f"has {last} days{leap}); {left} days remain.")
    assert d == d0 + datetime.timedelta(days=n)
    w0, wd = calendar.day_name[d0.weekday()], calendar.day_name[d.weekday()]
    k, shift = divmod(n, 7)
    assert calendar.day_name[(d0.weekday() + shift) % 7] == wd
    steps.append(f"Weekday: {n} = {k} * 7 + {shift}, so the weekday moves {shift} forward from {w0}: {wd}.")
    return doc(f"{d0.isoformat()} is a {w0}. What date is {n} days later, and which weekday is it?", steps,
               f"{d.isoformat()}, {wd}")


