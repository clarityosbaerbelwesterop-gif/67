def gsm8k_doc(row: dict) -> tuple[str | None, str]:
    sol, _, final = row["answer"].rpartition("####")
    final = final.strip().replace(",", "")
    if not re.fullmatch(r"-?\d+(\.\d+)?", final):
        return None, "final-not-numeric"
    for m in CALC.finditer(sol):
        lhs, rhs = m.group(1).strip(), m.group(2).strip().replace(",", "")
        if not SAFE_ARITH.match(lhs) or not re.fullmatch(r"-?\d+(\.\d+)?", rhs):
            return None, "unverifiable-annotation"
        try:
            got = eval(lhs, {"__builtins__": {}})  # noqa: S307 - digits and operators only
        except (SyntaxError, ZeroDivisionError):
            return None, "unverifiable-annotation"
        if abs(got - float(rhs)) > 1e-4 * max(1.0, abs(float(rhs))):
            return None, "wrong-annotation"
    steps = [ln.strip() for ln in CALC.sub("", sol).strip().splitlines() if ln.strip()]
    if not steps:
        return None, "empty"
    return doc(row["question"].strip(), steps, final), "ok"


AQUA_EQ = re.compile(r"((?:[(\s]*-?\d+(?:\.\d+)?[)\s]*[-+*/]\s*)+[(\s]*-?\d+(?:\.\d+)?[)\s]*)=\s*"
                     r"(-?\d[\d,]*(?:\.\d+)?)(?![\d.]*\s*[-+*/(%^])")
NUMBER = re.compile(r"\d+(?:\.\d+)?")


def checked_equations(text: str) -> int:
    """Number of pure-arithmetic equations `a op b ... = c` that re-compute correctly; -1 if one is wrong."""
    n = 0
    for m in AQUA_EQ.finditer(text):
        lhs, rhs = m.group(1), m.group(2).replace(",", "")
        if lhs.count("(") != lhs.count(")"):
            continue
        try:
            got = eval(lhs, {"__builtins__": {}})  # noqa: S307 - digits, operators and parentheses only
        except (SyntaxError, ZeroDivisionError):
            continue
        if abs(got - float(rhs)) > 1e-2 * max(1.0, abs(float(rhs))):
            return -1
        n += 1
    return n


AQUA_END = re.compile(r"(?:answer|ans|option|correct)[^A-Za-z0-9]{0,12}(?:is|:)?\s*\(?([A-E])\)?[\s.]*$", re.I)


def aqua_doc(row: dict) -> tuple[str | None, str]:
    q, rat, ok = row["question"].strip(), row["rationale"].strip(), row["correct"].strip()
    opts = row["options"]
    if not (20 <= len(q) <= 1500 and 60 <= len(rat) <= 3000) or len(opts) != 5 or ok not in "ABCDE" or not ok:
        return None, "length"
    text = q + rat + "".join(opts)
    if sum(32 <= ord(c) < 127 or c == "\n" for c in text) < 0.98 * len(text):
        return None, "characters"
    eq = checked_equations(rat)
    if eq < 0:
        return None, "wrong-equation"
    if eq < 2:
        return None, "unverified"
    nums = lambda t: {float(x) for x in NUMBER.findall(t.replace(",", ""))}  # noqa: E731
    if not nums(q) <= nums(rat):
        return None, "numbers-differ"
    lines = [ln.strip() for ln in rat.splitlines()
             if ln.strip() and not re.fullmatch(r"(?i)(explanation|solution|sol)\s*[:.]?", ln.strip())]
    m = AQUA_END.search(lines[-1])
    value = opts["ABCDE".index(ok)].split(")", 1)[-1].strip()
    if m:
        if m.group(1).upper() != ok:
            return None, "wrong-letter"
        lines = lines[:-1] or lines
    elif not (value and value in rat[-80:]):
        return None, "answer-not-reached"
    if len(lines) < 2 and len(rat) < 120:
        return None, "too-short"
    return doc(f"{q}\nOptions: {' '.join(opts)}", lines, f"{ok}) {value}"), "ok"


