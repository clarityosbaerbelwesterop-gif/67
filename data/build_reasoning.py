def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--synthetic-tokens", type=float, default=40e6)
    ap.add_argument("--workers", type=int, default=3)
    ap.add_argument("--seed", type=int, default=5)
    ap.add_argument("--sources", default="gsm8k,aqua,synthetic")
    ap.add_argument("--samples", type=int, default=0, help="print N samples per synthetic family and exit")
    ap.add_argument("--docs-only", action="store_true",
                    help="stop after data/cache/reasoning/docs-*.jsonl (corpus v6 tokenizes them itself)")
    a = ap.parse_args(argv)
    if a.samples:
        for fam, (fn, _) in FAMILIES.items():
            r = random.Random(a.seed)
            for sc in [0.2, 0.95][:a.samples]:
                for _ in range(20):
                    try:
                        print(f"===== {fam} (scale {sc})\n{fn(r, sc)}")
                        break
                    except Reject:
                        continue
        return 0

    spec = importlib.util.spec_from_file_location("corpus_v3", ROOT / "data" / "build_corpus_v3.py")
    v3 = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(v3)
    v2, bc = v3.v2, v3.bc
    v2.CACHE = CACHE
    near_spec = importlib.util.spec_from_file_location("corpus_v4", ROOT / "data" / "build_corpus_v4.py")
    v4 = importlib.util.module_from_spec(near_spec)
    near_spec.loader.exec_module(v4)

    dest = OUT / STORE
    if dest.exists() and not a.docs_only:
        raise SystemExit(f"{dest} exists; move it away first (nothing is overwritten)")
    CACHE.mkdir(parents=True, exist_ok=True)
    MANIFESTS.mkdir(parents=True, exist_ok=True)
    banned, eval_names = v3.banned_ngrams(EVALS, fetch_missing=False)
    log(f"{len(banned):,} banned 13-grams from {eval_names}")
    seen: set[str] = set()
    stats: dict[str, dict[str, int]] = {}
    chars: dict[str, int] = {}
    files = {s: (CACHE / f"docs-{s}.jsonl").open("w") for s in ("train", "val")}

    def emit(source: str, text: str | None, why: str) -> None:
        st = stats.setdefault(source, {})
        if text is not None:
            h = hashlib.sha1(" ".join(text.split()).encode()).hexdigest()
            if h in seen:
                why = "duplicate"
            elif bc.ngrams(text) & banned:
                why = "contaminated"
            else:
                seen.add(h)
                split = "val" if int(h[:4], 16) % 100 == 0 else "train"
                files[split].write(json.dumps({"h": h, "s": source, "t": text}) + "\n")
                chars[source] = chars.get(source, 0) + len(text)
        st[why] = st.get(why, 0) + 1

    srcs = set(a.sources.split(","))
    if "gsm8k" in srcs:
        for line in fetch("gsm8k-train").read_text().splitlines():
            if line.strip():
                emit("gsm8k-train", *gsm8k_doc(json.loads(line)))
        log(f"gsm8k-train: {stats['gsm8k-train']}")
    if "aqua" in srcs:
        near, qseen = v4.NearDup(), set()
        for line in fetch("aqua-train").read_text().splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            text, why = aqua_doc(row)
            if text is not None:
                qn = re.sub(r"[^a-z0-9]", "", row["question"].lower())
                sk = v4.sketch(row["question"])
                if qn in qseen or (sk is not None and near.seen(sk)):
                    text, why = None, "near-duplicate"
                qseen.add(qn)
            emit("aqua-train", text, why)
        log(f"aqua-train: {stats['aqua-train']}")
    fam_chars: dict[str, int] = {}
    if "synthetic" in srcs:
        target_chars, chunk, nxt = a.synthetic_tokens * CHARS_PER_TOKEN, 200, 0
        with Pool(a.workers) as pool:
            while sum(fam_chars.values()) < target_chars:
                jobs = [(nxt + k * chunk, chunk, a.seed) for k in range(a.workers * 4)]
                nxt += a.workers * 4 * chunk
                for res in pool.imap(_synth_chunk, jobs):
                    for fam, text in res:
                        emit(f"synthetic-{fam}", text, "ok")
                        fam_chars[fam] = fam_chars.get(fam, 0) + len(text)
                log(f"synthetic: {nxt:,} instances, ~{sum(fam_chars.values()) / CHARS_PER_TOKEN / 1e6:.1f} M tokens")
    for f in files.values():
        f.close()
    if a.docs_only:
        (MANIFESTS / "reasoning-docs.json").write_text(json.dumps({"per_source": stats, "chars": chars, "seed": a.seed,
                                                                   "evals_decontaminated_against": eval_names}, indent=1))
        log(f"docs only: {sum(st.get('ok', 0) for st in stats.values()):,} documents in {CACHE}")
        return 0

    stage = OUT / f".{STORE}-staging"
    shutil.rmtree(stage, ignore_errors=True)
    stage.mkdir(parents=True)
    n = {}
    for split, fname in (("train", "train.bin"), ("val", "train.val.bin")):
        with open(stage / fname, "wb") as f:
            n[split] = v2.tokenize_into(CACHE / f"docs-{split}.jsonl", f)
    mix = {s: st.get("ok", 0) for s, st in sorted(stats.items())}
    m = v2.finish_store(stage, n["train"][0], n["val"][0], mix)
    m.update(pipeline="data/build_reasoning.py (format Problem/Thinking/Answer; verified traces; exact dedup; "
                      "13-gram decontamination against HumanEval, MBPP, GSM8K test; ~1% val by hash)",
             docs=n["train"][1] + n["val"][1], sources=SOURCES, chars=chars)
    (stage / "manifest.json").write_text(json.dumps(m, indent=2))
    stage.rename(dest)
    (MANIFESTS / "reasoning.json").write_text(json.dumps({
        "store": STORE, "tokens": {"train": n["train"][0], "val": n["val"][0]}, "documents": m["docs"],
        "per_source": stats, "chars": chars, "sources": SOURCES, "seed": a.seed,
        "evals_decontaminated_against": eval_names, "sha256": m["sha256"]}, indent=1))
    log(f"store {STORE}: {n['train'][0]:,} train / {n['val'][0]:,} val tokens, {m['docs']:,} documents")
    return 0


if __name__ == "__main__":
    sys.exit(main())
