def doc(problem: str, steps: list[str], answer: str) -> str:
    sep = "\n" if "\n" in answer else " "
    return f"Problem: {problem}\n\nThinking:\n" + "\n".join(steps) + f"\n\nAnswer:{sep}{answer}\n"


