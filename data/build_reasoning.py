def g_gcd(r: random.Random, sc: float) -> str:
    a, b = r.randrange(10, 10 ** (3 + int(sc * 15))), r.randrange(10, 10 ** (3 + int(sc * 15)))
    if r.random() < 0.5:
        g = r.randrange(2, 10 ** (1 + int(sc * 4)))
        a, b = a * g, b * g
    a, b = max(a, b), min(a, b)
    if a == b:
        raise Reject
    if sc > 0.5:
        rows = [(a, 1, 0), (b, 0, 1)]
        steps = [f"Extended Euclid: keep rows (r, s, t) with r = s*{a} + t*{b}.",
                 f"Row 0: r = {a}, s = 1, t = 0.", f"Row 1: r = {b}, s = 0, t = 1."]
        while rows[-1][0]:
            (r0, s0, t0), (r1, s1, t1) = rows[-2], rows[-1]
            q = r0 // r1
            row = (r0 - q * r1, s0 - q * s1, t0 - q * t1)
            steps.append(f"Row {len(rows)}: q = {r0} // {r1} = {q}; r = {r0} - {q}*{r1} = {row[0]}, "
                         f"s = {s0} - {q}*({s1}) = {row[1]}, t = {t0} - {q}*({t1}) = {row[2]}.")
            rows.append(row)
        g, s, t = rows[-2]
        assert g == math.gcd(a, b) and s * a + t * b == g
        steps.append(f"The last nonzero remainder is {g}. Check: {s}*{a} + ({t})*{b} = {s * a + t * b}.")
        return doc(f"Find gcd({a}, {b}) and integers s, t with s*{a} + t*{b} = gcd.", steps,
                   f"gcd = {g}, s = {s}, t = {t}")
    steps, x, y = [], a, b
    while y:
        q, rr = divmod(x, y)
        steps.append(f"{x} = {q} * {y} + {rr}.")
        x, y = y, rr
    assert x == math.gcd(a, b)
    steps.append(f"The remainder is 0, so the gcd is the last divisor, {x}.")
    return doc(f"Find gcd({a}, {b}) with the Euclidean algorithm.", steps, str(x))


def g_modpow(r: random.Random, sc: float) -> str:
    m = r.randrange(7, 10 ** (2 + int(sc * 7)))
    b = r.randrange(2, m)
    e = r.randrange(2 ** (3 + int(sc * 30)), 2 ** (4 + int(sc * 30)))
    bits = bin(e)[2:]
    steps = [f"{e} in binary is {bits}. Start with result = 1 and read the bits from the left: square for every "
             f"bit, then multiply by {b} if the bit is 1 (all mod {m})."]
    res = 1
    for i, bit in enumerate(bits):
        sq = res * res % m
        line = f"Bit {i + 1} = {bit}: {res}^2 mod {m} = {sq}"
        res = sq
        if bit == "1":
            res = res * b % m
            line += f"; {sq} * {b} mod {m} = {res}"
        steps.append(line + ".")
    assert res == pow(b, e, m)
    return doc(f"Compute {b}^{e} mod {m}.", steps, str(res))


DIG = "0123456789ABCDEF"


def g_base(r: random.Random, sc: float) -> str:
    base = r.choice([2, 3, 5, 7, 8, 12, 16])
    n = r.randrange(10 ** (1 + int(sc * 12)), 10 ** (2 + int(sc * 12)))
    if base == 2:
        n = r.randrange(2 ** (4 + int(sc * 30)), 2 ** (5 + int(sc * 30)))
    rep, x = [], n
    while x:
        rep.append(DIG[x % base])
        x //= base
    s = "".join(reversed(rep))
    assert int(s, base) == n
    if r.random() < 0.5:
        steps, x = [], n
        while x:
            q, rr = divmod(x, base)
            steps.append(f"{x} / {base} = {q} remainder {rr}" + (f" (digit {DIG[rr]})" if rr > 9 else "") + ".")
            x = q
        steps.append(f"Reading the remainders from last to first gives {s}.")
        return doc(f"Convert {n} from base 10 to base {base}.", steps, s)
    steps, acc = [f"Horner's rule: start with 0, then for each digit multiply by {base} and add the digit."], 0
    for ch in s:
        new = acc * base + int(ch, 16)
        steps.append(f"Digit {ch}: {acc} * {base} + {int(ch, 16)} = {new}.")
        acc = new
    assert acc == n
    return doc(f"Convert {s} from base {base} to base 10.", steps, str(n))


SMALL_PRIMES = [p for p in range(2, 2000) if all(p % q for q in range(2, int(p ** 0.5) + 1))]


def g_factor(r: random.Random, sc: float) -> str:
    fs = sorted(r.choice(SMALL_PRIMES[:20 + int(sc * 150)]) for _ in range(2 + int(sc * 6 * r.random())))
    n = math.prod(fs)
    if n < 12:
        raise Reject
    steps, rem, found = [], n, []
    for p in SMALL_PRIMES:
        if p * p > rem:
            break
        if rem % p:
            if p < 30 or sc > 0.6:
                steps.append(f"{p} does not divide {rem}.")
            continue
        while rem % p == 0:
            steps.append(f"{rem} / {p} = {rem // p}.")
            rem //= p
            found.append(p)
    if rem > 1:
        steps.append(f"No prime up to the square root of {rem} divides it, so {rem} is prime.")
        found.append(rem)
    assert math.prod(found) == n and found == fs
    parts = [f"{p}^{found.count(p)}" if found.count(p) > 1 else str(p) for p in sorted(set(found))]
    return doc(f"Find the prime factorisation of {n}.", steps, " * ".join(parts))


