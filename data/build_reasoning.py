def g_sort(r: random.Random, sc: float) -> str:
    xs = [r.randint(-50, 99) for _ in range(4 + int(sc * 26))]
    if sc > 0.6 and r.random() < 0.5:
        steps = []

        def ms(a: list[int]) -> list[int]:
            if len(a) <= 1:
                return a
            m = len(a) // 2
            left, right = ms(a[:m]), ms(a[m:])
            out, i, j = [], 0, 0
            while i < len(left) and j < len(right):
                if left[i] <= right[j]:
                    out.append(left[i])
                    i += 1
                else:
                    out.append(right[j])
                    j += 1
            out += left[i:] + right[j:]
            steps.append(f"Merge {left} and {right} into {out}.")
            return out

        res = ms(list(xs))
        assert res == sorted(xs)
        return doc(f"Sort {xs} in ascending order with merge sort. Show every merge.", steps, str(res))
    a, steps = list(xs), []
    for i in range(1, len(a)):
        v, j = a[i], i - 1
        moved = []
        while j >= 0 and a[j] > v:
            a[j + 1] = a[j]
            moved.append(a[j])
            j -= 1
        a[j + 1] = v
        what = f"shift {', '.join(map(str, moved))} one place right" if moved else "no shift needed"
        steps.append(f"Insert {v}: {what}. List: {a}.")
    assert a == sorted(xs)
    return doc(f"Sort {xs} in ascending order with insertion sort. Show the list after every insertion.", steps,
               str(a))


def g_bsearch(r: random.Random, sc: float) -> str:
    xs = sorted(r.sample(range(0, 1000 + int(sc * 9000)), 8 + int(sc * 120)))
    t = r.choice(xs) if r.random() < 0.7 else r.randrange(0, 1000 + int(sc * 9000))
    lo, hi, steps, found = 0, len(xs) - 1, [], -1
    while lo <= hi:
        mid = (lo + hi) // 2
        if xs[mid] == t:
            steps.append(f"lo = {lo}, hi = {hi}, mid = {mid}: xs[{mid}] = {xs[mid]} equals {t}. Found.")
            found = mid
            break
        if xs[mid] < t:
            steps.append(f"lo = {lo}, hi = {hi}, mid = {mid}: xs[{mid}] = {xs[mid]} < {t}, so lo = {mid + 1}.")
            lo = mid + 1
        else:
            steps.append(f"lo = {lo}, hi = {hi}, mid = {mid}: xs[{mid}] = {xs[mid]} > {t}, so hi = {mid - 1}.")
            hi = mid - 1
    if found < 0:
        steps.append(f"lo = {lo} > hi = {hi}: the range is empty, {t} is not in the list.")
    assert (found >= 0 and xs[found] == t) or (found < 0 and t not in xs)
    return doc(f"Use binary search to find the index of {t} in the sorted list xs = {xs} (index from 0). "
               f"Answer -1 if it is absent.", steps, str(found))


MOVES = {"U": (-1, 0), "D": (1, 0), "L": (0, -1), "R": (0, 1)}


def g_bfs(r: random.Random, sc: float) -> str:
    h, w = 4 + int(sc * 10 * r.random() + sc * 2), 4 + int(sc * 10 * r.random() + sc * 2)
    dens = r.uniform(0.15, 0.32)
    g = [["#" if r.random() < dens else "." for _ in range(w)] for _ in range(h)]
    cells = [(i, j) for i in range(h) for j in range(w)]
    s, e = r.sample(cells, 2)
    g[s[0]][s[1]], g[e[0]][e[1]] = "S", "E"
    grid = "\n".join("".join(row) for row in g)
    dist, par, frontier, steps = {s: 0}, {}, [s], []
    while frontier and e not in dist:
        nxt = []
        for c in frontier:
            for mv, (di, dj) in MOVES.items():
                n = (c[0] + di, c[1] + dj)
                if 0 <= n[0] < h and 0 <= n[1] < w and g[n[0]][n[1]] != "#" and n not in dist:
                    dist[n], par[n] = dist[c] + 1, (c, mv)
                    nxt.append(n)
        if nxt:
            shown = ", ".join(f"({i},{j})" for i, j in nxt[:24]) + (f" and {len(nxt) - 24} more" if len(nxt) > 24 else "")
            steps.append(f"Distance {dist[nxt[0]]}: {shown}.")
        frontier = nxt
    # independent check: BFS from E must give the same distance
    d2, q = {e: 0}, deque([e])
    while q:
        c = q.popleft()
        for di, dj in MOVES.values():
            n = (c[0] + di, c[1] + dj)
            if 0 <= n[0] < h and 0 <= n[1] < w and g[n[0]][n[1]] != "#" and n not in d2:
                d2[n] = d2[c] + 1
                q.append(n)
    if e not in dist:
        assert s not in d2
        steps.append("No new cells can be reached and E was not reached.")
        ans = "unreachable"
    else:
        path, c = [], e
        while c != s:
            c, mv = par[c]
            path.append(mv)
        path = "".join(reversed(path))
        assert len(path) == dist[e] == d2[s]
        steps.append(f"E at ({e[0]},{e[1]}) is reached at distance {dist[e]}. Following the parents back gives the "
                     f"moves {path}.")
        ans = f"{dist[e]} moves: {path}"
    if len(steps) < 2:
        raise Reject
    return doc("Find a shortest path from S to E in the grid below. Moves are U, D, L, R; # is a wall; cells are "
               f"(row, column) from (0,0) at the top left. Use breadth-first search.\n\n{grid}", steps, ans)


def g_dijkstra(r: random.Random, sc: float) -> str:
    n = 5 + int(sc * 12)
    names = [chr(65 + i) for i in range(n)]
    edges = {}
    for i in range(1, n):
        edges[(names[r.randrange(i)], names[i])] = r.randint(1, 20)
    for _ in range(int(n * r.uniform(0.5, 1.5))):
        a, b = r.sample(names, 2)
        if (a, b) not in edges and (b, a) not in edges:
            edges[(a, b)] = r.randint(1, 20)
    adj = {v: [] for v in names}
    for (a, b), wgt in edges.items():
        adj[a].append((b, wgt))
        adj[b].append((a, wgt))
    src, dst = names[0], names[-1]
    dist, prev, done, pq, steps = {src: 0}, {}, set(), [(0, src)], []
    while pq:
        d, u = heapq.heappop(pq)
        if u in done:
            continue
        done.add(u)
        rel = []
        for v, wgt in sorted(adj[u]):
            if v in done:
                continue
            nd = d + wgt
            if nd < dist.get(v, math.inf):
                old = dist.get(v)
                dist[v], prev[v] = nd, u
                heapq.heappush(pq, (nd, v))
                rel.append(f"{v}: {d}+{wgt} = {nd} < {'inf' if old is None else old}, update")
            else:
                rel.append(f"{v}: {d}+{wgt} = {nd} >= {dist[v]}, keep")
        steps.append(f"Take {u} (distance {d})." + (" Relax " + "; ".join(rel) + "." if rel else ""))
        if u == dst:
            break
    # independent check: Bellman-Ford
    bf = {v: math.inf for v in names}
    bf[src] = 0
    for _ in range(n - 1):
        for (a, b), wgt in edges.items():
            bf[b] = min(bf[b], bf[a] + wgt)
            bf[a] = min(bf[a], bf[b] + wgt)
    assert dist[dst] == bf[dst]
    path, c = [dst], dst
    while c != src:
        c = prev[c]
        path.append(c)
    edge_list = ", ".join(f"{a}-{b} {wgt}" for (a, b), wgt in edges.items())
    return doc(f"Undirected graph with weighted edges {edge_list}. Find the shortest distance from {src} to {dst} "
               "with Dijkstra's algorithm and give the path.", steps,
               f"{dist[dst]} via {'-'.join(reversed(path))}")


