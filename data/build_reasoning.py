def synth(idx: int, seed: int) -> tuple[str, str]:
    r = random.Random(seed * 1_000_003 + idx)
    names = list(FAMILIES)
    fam = r.choices(names, weights=[FAMILIES[n][1] for n in names])[0]
    for _ in range(20):
        sc = r.uniform(0.85, 1.0) if r.random() < 0.125 else r.random() ** 1.6
        try:
            return fam, FAMILIES[fam][0](r, sc)
        except Reject:
            continue
    raise RuntimeError(f"{fam}: no instance after 20 draws")


def _synth_chunk(args: tuple[int, int, int]) -> list[tuple[str, str]]:
    start, n, seed = args
    return [synth(i, seed) for i in range(start, start + n)]


