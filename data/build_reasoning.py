PREC = {"+": 1, "-": 1, "*": 2}


def _tree(r: random.Random, n: int):
    if n <= 0:
        return r.randint(-9, 20) if r.random() < 0.15 else r.randint(1, 20)
    k = r.randint(0, n - 1)
    return [r.choice("+-*+-"), _tree(r, k), _tree(r, n - 1 - k)]


def _show(t, parent: str | None = None, right: bool = False) -> str:
    if isinstance(t, int):
        return f"({t})" if t < 0 else str(t)
    op, a, b = t
    s = f"{_show(a, op)} {op} {_show(b, op, True)}"
    if parent and (PREC[op] < PREC[parent] or (right and PREC[op] == PREC[parent])):
        return f"({s})"
    return s


def _reduce(t):
    """Reduce the leftmost operation whose operands are both numbers; returns (new tree, done)."""
    if isinstance(t, int):
        return t, False
    op, a, b = t
    if isinstance(a, int) and isinstance(b, int):
        return (a + b if op == "+" else a - b if op == "-" else a * b), True
    na, done = _reduce(a)
    if done:
        return [op, na, b], True
    nb, done = _reduce(b)
    return [op, a, nb], done


def g_expr(r: random.Random, sc: float) -> str:
    t = _tree(r, 2 + int(sc * 14))
    text = _show(t)
    want = eval(text, {"__builtins__": {}})  # noqa: S307 - generated integer expression
    if abs(want) >= 10 ** 12:
        raise Reject
    steps = []
    while not isinstance(t, int):
        t, _ = _reduce(t)
        steps.append(f"= {_show(t)}")
    assert t == want
    return doc(f"Evaluate {text}. Reduce one operation per step, respecting precedence and left-to-right order.",
               steps, str(t))


VARS = "xyzw"


def _eq(row: list[Fraction], n: int) -> str:
    terms = []
    for k in range(n):
        c = row[k]
        if c == 0:
            continue
        mag = abs(c)
        coef = "" if mag == 1 else f"{mag}" if mag.denominator == 1 else f"({mag})"
        terms.append((" - " if c < 0 else " + ") + f"{coef}{VARS[k]}")
    lhs = "".join(terms).lstrip(" +") or "0"
    lhs = "-" + lhs[2:] if lhs.startswith("- ") else lhs
    return f"{lhs} = {row[n]}"


def _fr(x: Fraction) -> str:
    return str(x) if x >= 0 and x.denominator == 1 else f"({x})"


def g_linsys(r: random.Random, sc: float) -> str:
    n = 2 if sc < 0.4 else 3 if sc < 0.85 else 4
    sol = [r.randint(-9, 9) for _ in range(n)]
    rows = []
    for _ in range(n):
        co = [r.randint(-6, 6) for _ in range(n)]
        rows.append([Fraction(c) for c in co] + [Fraction(sum(c * s for c, s in zip(co, sol)))])
    m = [row[:] for row in rows]
    steps = []
    for col in range(n):
        piv = next((k for k in range(col, n) if m[k][col] != 0), None)
        if piv is None:
            raise Reject
        if piv != col:
            m[col], m[piv] = m[piv], m[col]
            steps.append(f"Swap equations {col + 1} and {piv + 1}.")
        for k in range(col + 1, n):
            if m[k][col] == 0:
                continue
            f = m[k][col] / m[col][col]
            m[k] = [a - f * b for a, b in zip(m[k], m[col])]
            steps.append(f"E{k + 1} = E{k + 1} - ({f})*E{col + 1}: {_eq(m[k], n)}.")
    val = [Fraction(0)] * n
    for k in range(n - 1, -1, -1):
        rest = sum(m[k][j] * val[j] for j in range(k + 1, n))
        val[k] = (m[k][n] - rest) / m[k][k]
        num = _fr(m[k][n]) if rest == 0 else f"({_fr(m[k][n])} - {_fr(rest)})"
        steps.append(f"From E{k + 1}: {VARS[k]} = {num} / {_fr(m[k][k])} = {val[k]}.")
    assert val == [Fraction(s) for s in sol]
    for row in rows:
        assert sum(row[k] * val[k] for k in range(n)) == row[n]
    steps.append("Substituting the values into every original equation checks out.")
    system = "; ".join(_eq(row, n) for row in rows)
    return doc(f"Solve the system {system} by elimination.", steps,
               ", ".join(f"{VARS[k]} = {val[k]}" for k in range(n)))


