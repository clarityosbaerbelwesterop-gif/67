SAFE = {"range": range, "len": len, "min": min, "max": max, "abs": abs, "str": str, "sum": sum, "sorted": sorted}


class _Limit(Exception):
    pass


class Prog:
    INTS = ["a", "b", "c", "x", "y", "n", "total", "count", "acc", "best"]

    def __init__(self, r: random.Random, sc: float):
        self.r, self.sc = r, sc
        self.ints: list[str] = []
        self.lists: list[str] = []
        self.has_s = False

    def expr(self, depth: int = 0) -> str:
        r = self.r
        if depth > 1 or not self.ints or r.random() < 0.35:
            return r.choice(self.ints) if self.ints and r.random() < 0.6 else str(r.randint(0, 9))
        op = r.choice(["+", "-", "*", "%", "//", "+"])
        right = str(r.randint(2, 7)) if op in ("%", "//") else self.expr(depth + 1)
        e = f"{self.expr(depth + 1)} {op} {right}"
        return f"({e})" if depth else e

    def cond(self, loopv: list[str]) -> str:
        r = self.r
        pool = self.ints + loopv
        left = r.choice(pool) if pool else "0"
        if r.random() < 0.3 and pool:
            return f"{left} % {r.randint(2, 4)} == {r.randint(0, 1)}"
        return f"{left} {r.choice(['<', '>', '<=', '>=', '==', '!='])} {r.randint(0, 12)}"

    def stmt(self, ind: str, depth: int, loopv: list[str]) -> list[str]:
        r = self.r
        k = r.random()
        if depth < 2 and k < 0.2 and len(loopv) < 2:
            v = "i" if "i" not in loopv else "j"
            hi = r.randint(2, 3 + int(self.sc * 7))
            head = f"{ind}for {v} in range({hi}):" if r.random() < 0.7 else \
                f"{ind}for {v} in range({r.randint(0, 2)}, {hi + 2}):"
            return [head] + self.block(ind + "    ", depth + 1, loopv + [v], r.randint(1, 3))
        if depth < 2 and k < 0.34:
            out = [f"{ind}if {self.cond(loopv)}:"] + self.block(ind + "    ", depth + 1, loopv, r.randint(1, 2))
            if r.random() < 0.5:
                out += [f"{ind}else:"] + self.block(ind + "    ", depth + 1, loopv, r.randint(1, 2))
            return out
        if k < 0.42 and self.lists:
            lst = r.choice(self.lists)
            return [f"{ind}{lst}.append({self.expr() if r.random() < 0.6 or not loopv else r.choice(loopv)})"]
        if k < 0.47 and self.lists and (self.ints or loopv):
            lst, tgt = r.choice(self.lists), r.choice(self.ints) if self.ints else "acc"
            if tgt not in self.ints:
                self.ints.append(tgt)
                return [f"{ind}{tgt} = len({lst})"]
            return [f"{ind}{tgt} += {lst}[-1] if {lst} else 0"]
        if k < 0.52 and self.has_s:
            src = r.choice(loopv) if loopv else r.choice(self.ints) if self.ints else "0"
            return [f"{ind}s += str({src})" if r.random() < 0.7 else f"{ind}s = s[-6:]"]
        if k < 0.58 and self.ints and depth > 0:
            v = r.choice(self.ints)
            return [f"{ind}{v} = max({v}, {r.choice(loopv) if loopv else self.expr(1)})"]
        names = [n for n in self.INTS if n not in self.ints]
        if names and (r.random() < 0.3 or not self.ints) and depth == 0:
            v = r.choice(names)
            line = f"{ind}{v} = {self.expr()}"
            self.ints.append(v)
            return [line]
        if not self.ints:
            v = r.choice(self.INTS)
            self.ints.append(v)
            return [f"{ind}{v} = {r.randint(0, 9)}"]
        v = r.choice(self.ints)
        rhs = r.choice(loopv) if loopv and r.random() < 0.4 else self.expr(1)
        return [f"{ind}{v} {r.choice(['+=', '-=', '=', '+='])} {rhs}"]

    def block(self, ind: str, depth: int, loopv: list[str], n: int) -> list[str]:
        out = []
        for _ in range(n):
            out += self.stmt(ind, depth, loopv)
        return out

    def program(self) -> str:
        r = self.r
        lines = []
        for _ in range(r.randint(1, 3)):
            lines += self.stmt("", 0, [])
        if r.random() < 0.5:
            name = r.choice(["xs", "ys", "stack"])
            self.lists.append(name)
            lines.append(f"{name} = {[r.randint(0, 9) for _ in range(r.randint(0, 3))]}")
        if r.random() < 0.3:
            self.has_s = True
            lines.append('s = ""')
        lines += self.block("", 0, [], r.randint(2, 3 + int(self.sc * 5)))
        shown = (self.ints[-2:] if self.ints else []) + self.lists[:1] + (["s"] if self.has_s else [])
        if not shown:
            raise Reject
        lines.append(f"print({', '.join(shown)})" if r.random() < 0.6 else
                     "\n".join(f"print({v})" for v in shown))
        return "\n".join(lines) + "\n"


def _run(src: str, limit: int, trace: bool):
    code = compile(src, "<prog>", "exec")
    out, events = [], []
    g = {"__builtins__": dict(SAFE)}
    g["__builtins__"]["print"] = lambda *a: out.append((len(events) - 1, " ".join(map(str, a))))

    def snap() -> dict:
        return {k: (list(v) if isinstance(v, list) else v) for k, v in g.items() if k != "__builtins__"}

    def tr(frame, ev, arg):
        if frame.f_code.co_filename != "<prog>":
            return None
        if ev == "line":
            st = snap()
            events.append((frame.f_lineno, st))
            # bounded values: repeated products would otherwise grow to huge integers before the step limit
            if len(events) > limit or any(isinstance(v, int) and abs(v) > 10 ** 12 for v in st.values()):
                raise _Limit
        return tr

    if trace:
        sys.settrace(tr)
    try:
        exec(code, g)  # noqa: S102 - program generated above from a closed grammar, builtins restricted
    finally:
        sys.settrace(None)
    return out, events, snap()


def _effect(code: str, before: dict, after: dict) -> str:
    head = code.split()[0]
    if head in ("if", "while", "elif"):
        cond = code[len(head):].rstrip(":").strip()
        return f"condition {cond} is {bool(eval(cond, {'__builtins__': SAFE}, dict(before)))}"  # noqa: S307
    ch = [f"{k} = {after[k]!r}" for k in after if k not in before or before[k] != after[k]]
    if head == "for" and not ch:
        return "loop finished"
    return ", ".join(ch) if ch else "no change"


def g_program(r: random.Random, sc: float) -> str:
    limit, least = 12 + int(sc * 260), 4 + int(sc * sc * 110)
    for _ in range(80):
        try:
            src = Prog(r, sc).program()
            out, events, final = _run(src, limit, trace=True)
        except (_Limit, Reject, ZeroDivisionError, IndexError, TypeError, ValueError, NameError, RecursionError):
            continue
        vals = [v for _, st in events for v in st.values()] + list(final.values())
        if (len(events) < least or not out or any(isinstance(v, int) and abs(v) > 10 ** 9 for v in vals)
                or any(isinstance(v, (list, str)) and len(v) > 16 for v in vals)):
            continue
        assert [t for _, t in _run(src, 10 ** 6, trace=False)[0]] == [t for _, t in out]
        lines = src.splitlines()
        steps = []
        for k, (ln, before) in enumerate(events):
            after = events[k + 1][1] if k + 1 < len(events) else final
            code = lines[ln - 1].strip()
            eff = _effect(code, before, after)
            printed = [t for i, t in out if i == k]
            if printed:
                eff = (eff + "; " if eff != "no change" else "") + "prints " + " | ".join(printed)
            steps.append(f"{k + 1}. `{code}`: {eff}")
        ans = "\n".join(t for _, t in out)
        return doc(f"Trace this Python program step by step and give its exact output.\n\n```python\n{src}```",
                   steps, ans)
    raise Reject


