def g_edit(r: random.Random, sc: float) -> str:
    alpha = r.choice(["abc", "abcd", "acgt", "xyz"])
    a = "".join(r.choice(alpha) for _ in range(3 + int(sc * 11)))
    b = "".join(r.choice(alpha) for _ in range(3 + int(sc * 11)))
    prev = list(range(len(b) + 1))
    steps = [f"Row 0 (empty prefix of '{a}'): {' '.join(map(str, prev))}."]
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        steps.append(f"Row {i} ('{a[:i]}'): {' '.join(map(str, cur))}.")
        prev = cur

    @lru_cache(None)
    def ed(i: int, j: int) -> int:
        if not i or not j:
            return i + j
        return min(ed(i - 1, j) + 1, ed(i, j - 1) + 1, ed(i - 1, j - 1) + (a[i - 1] != b[j - 1]))

    assert prev[-1] == ed(len(a), len(b))
    steps.append(f"The bottom-right cell is {prev[-1]}.")
    return doc(f"Compute the edit distance (insert, delete, substitute, each cost 1) between '{a}' and '{b}'. "
               f"Fill the DP table row by row; columns are the prefixes of '{b}' from empty to full.", steps,
               str(prev[-1]))


def g_lcs(r: random.Random, sc: float) -> str:
    alpha = r.choice(["abc", "abcd", "acgt"])
    a = "".join(r.choice(alpha) for _ in range(4 + int(sc * 10)))
    b = "".join(r.choice(alpha) for _ in range(4 + int(sc * 10)))
    t = [[0] * (len(b) + 1) for _ in range(len(a) + 1)]
    steps = []
    for i in range(1, len(a) + 1):
        for j in range(1, len(b) + 1):
            t[i][j] = t[i - 1][j - 1] + 1 if a[i - 1] == b[j - 1] else max(t[i - 1][j], t[i][j - 1])
        steps.append(f"Row {i} ('{a[i - 1]}'): {' '.join(map(str, t[i][1:]))}.")
    i, j, out = len(a), len(b), []
    while i and j:
        if a[i - 1] == b[j - 1]:
            out.append(a[i - 1])
            i, j = i - 1, j - 1
        elif t[i - 1][j] >= t[i][j - 1]:
            i -= 1
        else:
            j -= 1
    s = "".join(reversed(out))

    def sub(x: str, y: str) -> bool:
        it = iter(y)
        return all(c in it for c in x)

    assert len(s) == t[-1][-1] and sub(s, a) and sub(s, b)
    steps.append(f"The length is {len(s)}. Walking back from the last cell (diagonal on a match, else towards the "
                 f"larger neighbour, up on a tie) gives '{s}'.")
    return doc(f"Find the length of a longest common subsequence of '{a}' and '{b}' and one such subsequence. "
               f"Row i lists the table for the prefix of length i of '{a}' against the prefixes of '{b}'.", steps,
               f"{len(s)}, '{s}'")


def g_knapsack(r: random.Random, sc: float) -> str:
    n, cap = 3 + int(sc * 6), 5 + int(sc * 20)
    items = [(r.randint(1, max(2, cap // 2)), r.randint(1, 30)) for _ in range(n)]
    best = [0] * (cap + 1)
    keep = [[False] * (cap + 1) for _ in range(n)]
    steps = []
    for k, (wt, val) in enumerate(items):
        new = best[:]
        for c in range(wt, cap + 1):
            if best[c - wt] + val > new[c]:
                new[c], keep[k][c] = best[c - wt] + val, True
        best = new
        steps.append(f"After item {k + 1} (weight {wt}, value {val}): best value by capacity 0..{cap} is "
                     f"{' '.join(map(str, best))}.")
    c, chosen = cap, []
    for k in range(n - 1, -1, -1):
        if keep[k][c]:
            chosen.append(k + 1)
            c -= items[k][0]
    chosen.reverse()
    brute = max(sum(items[k][1] for k in s) for m in range(n + 1) for s in combinations(range(n), m)
                if sum(items[k][0] for k in s) <= cap)
    assert best[cap] == brute == sum(items[k - 1][1] for k in chosen)
    steps.append(f"The best value for capacity {cap} is {best[cap]}; tracing the choices back gives items {chosen}.")
    desc = "; ".join(f"item {k + 1}: weight {wt}, value {val}" for k, (wt, val) in enumerate(items))
    return doc(f"0/1 knapsack with capacity {cap} and {desc}. Find the maximum total value and the items.", steps,
               f"{best[cap]} with items {chosen}")


