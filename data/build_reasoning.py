PLACES = ["ones", "tens", "hundreds", "thousands"]


def _place(i: int) -> str:
    return PLACES[i] if i < len(PLACES) else f"10^{i}"


def g_add(r: random.Random, sc: float) -> str:
    k = 2 + int(sc * 4 * r.random())
    nd = 2 + int(sc * 38)
    nums = [r.randrange(10 ** (d - 1), 10 ** d) for d in (max(1, nd - r.randrange(3)) for _ in range(k))]
    strs = [str(n) for n in nums]
    steps, carry, digits = [], 0, []
    for pos in range(max(map(len, strs))):
        col = [int(s[-1 - pos]) for s in strs if len(s) > pos]
        tot = sum(col) + carry
        terms = " + ".join(map(str, col)) + (f" + carry {carry}" if carry else "")
        steps.append(f"Column {pos + 1} ({_place(pos)}): {terms} = {tot}. Write {tot % 10}, carry {tot // 10}.")
        digits.append(tot % 10)
        carry = tot // 10
    if carry:
        steps.append(f"The final carry {carry} goes in front.")
        digits.extend(int(c) for c in reversed(str(carry)))
    res = int("".join(map(str, reversed(digits))))
    assert res == sum(nums)
    steps.append(f"Reading the digits from left to right gives {res}.")
    return doc(f"Compute {' + '.join(strs)} by column addition.", steps, str(res))


def _mul_digit(a: int, d: int) -> tuple[list[str], int]:
    parts, carry, out = [], 0, []
    for ch in reversed(str(a)):
        v = int(ch) * d + carry
        parts.append(f"{ch} * {d}" + (f" + {carry}" if carry else "") + f" = {v}, write {v % 10} carry {v // 10}")
        out.append(v % 10)
        carry = v // 10
    if carry:
        out.extend(int(c) for c in reversed(str(carry)))
    p = int("".join(map(str, reversed(out))))
    assert p == a * d
    return parts, p


def g_mul(r: random.Random, sc: float) -> str:
    da, db = 2 + int(sc * 12 * r.random() + sc * 2), 1 + int(sc * 7 * r.random() + 1)
    a, b = r.randrange(10 ** (da - 1), 10 ** da), r.randrange(10 ** (db - 1), 10 ** db)
    steps, running = [f"Multiply {a} by each digit of {b}, from the right, and add the shifted results."], 0
    for i, ch in enumerate(reversed(str(b))):
        d = int(ch)
        if d == 0:
            steps.append(f"Digit {i + 1} of {b} is 0: the partial product is 0.")
            continue
        parts, p = _mul_digit(a, d)
        if len(str(a)) <= 10:
            steps.append(f"{a} * {d}: " + "; ".join(parts) + f". So {a} * {d} = {p}.")
        else:
            steps.append(f"{a} * {d} = {p}.")
        shifted = p * 10 ** i
        running += shifted
        if i:
            steps.append(f"Shift by {i} place{'s' if i > 1 else ''}: {shifted}. Running total: {running}.")
        else:
            steps.append(f"Running total: {running}.")
    assert running == a * b
    return doc(f"Compute {a} * {b} by long multiplication.", steps, str(running))


def g_div(r: random.Random, sc: float) -> str:
    dd = 1 + int(sc * 4 * r.random())
    dv = r.randrange(max(2, 10 ** (dd - 1)), 10 ** dd)
    n = r.randrange(10 ** (1 + int(sc * 28)), 10 ** (2 + int(sc * 28)))
    rem, qd, steps = 0, [], []
    for ch in str(n):
        cur = rem * 10 + int(ch)
        q = cur // dv
        rem = cur - q * dv
        qd.append(str(q))
        steps.append(f"Bring down {ch}: {cur}. {cur} / {dv} = {q} ({q} * {dv} = {q * dv}), remainder {rem}.")
    q = int("".join(qd))
    assert q == n // dv and rem == n % dv
    steps.append(f"The quotient digits read {''.join(qd)}, which is {q}; the last remainder is {rem}.")
    ans = f"{q} remainder {rem}" if rem else str(q)
    return doc(f"Divide {n} by {dv} using long division. Give the quotient and the remainder.", steps, ans)


