def tgz(files: dict) -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tf:
        for name, text in files.items():
            data = text.encode()
            ti = tarfile.TarInfo(name)
            ti.size = len(data)
            tf.addfile(ti, io.BytesIO(data))
    return buf.getvalue()


def test_shares_are_disjoint_complete_and_deterministic():
    entries = [{"task": f"crates:p{i}", "status": "ok", "url": f"u{i}.crate", "sha256": "x"} for i in range(10)]
    entries += [{"task": "npm:bad", "status": "rejected-licence", "url": None, "sha256": None}]
    shares = [S.share(entries[::-1], i, 3) for i in range(3)]
    tasks = [e["task"] for s in shares for e in s]
    assert sorted(tasks) == sorted(f"crates:p{i}" for i in range(10)) and len(set(tasks)) == 10
    assert shares == [S.share(entries, i, 3) for i in range(3)]


@pytest.mark.skipif(not S.FORGE.exists(), reason="needs target/release/forge")
def test_build_skips_changed_archives_and_writes_a_store(tmp_path, monkeypatch):
    good = tgz({"pkg/src/handlers.py": GOOD, "pkg/src/gen.py": "# @generated by protoc\n" + GOOD.replace("handler", "h2")})
    blobs = {"a.tar.gz": good, "b.tar.gz": tgz({"pkg/x.py": GOOD.replace("handler", "other")})}
    man = [{"task": "pypi:a", "status": "ok", "url": "a.tar.gz", "sha256": hashlib.sha256(good).hexdigest()},
           {"task": "pypi:b", "status": "ok", "url": "b.tar.gz", "sha256": "0" * 64}]  # upload changed since the manifest
    (tmp_path / "m.json").write_text(json.dumps(man))
    monkeypatch.setattr(S.reg, "fetch", lambda url, **k: blobs.get(url))
    out = tmp_path / "shard"
    assert S.main(["--shard", "0", "--of", "1", "--out", str(out), "--manifest", str(tmp_path / "m.json"), "--no-decontam"]) == 0
    m = json.loads((out / "manifest.json").read_text())
    assert m["drops"]["sha_mismatch"] == 1 and m["drops"]["generated"] == 1
    assert [p["task"] for p in m["packages"]] == ["pypi:a"] and m["packages"][0]["kept"] == 1
    meta = json.loads((out / "train.meta.json").read_text())
    assert meta["tokens"] + meta["val_tokens"] == ((out / "train.bin").stat().st_size + (out / "train.val.bin").stat().st_size) // 2 > 100
    assert (out / "tokenizer.json").read_bytes() == S.TOKENIZER.read_bytes()
